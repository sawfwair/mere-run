#!/usr/bin/env python3
"""Compare mere.run unified-AV audio against an upstream LTX-2 output.

The script is intentionally media-file based: run the same prompt/seed through
mere.run and upstream LTX-2, then compare the produced MP4s. It reports both
container/codec metadata and decoded waveform stats so odd audio can be traced
to either the model waveform or the mux/encode step.
"""

from __future__ import annotations

import argparse
import array
import json
import math
import os
import re
import shutil
import struct
import subprocess
import sys
from pathlib import Path
from typing import Any


def main() -> int:
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[1]

    try:
        ffprobe = resolve_tool("MERERUN_FFPROBE", "ffprobe")
        ffmpeg = resolve_tool("MERERUN_FFMPEG", "ffmpeg")

        mere = analyze_media(Path(args.mere), ffprobe, ffmpeg)
        ltx = analyze_media(Path(args.ltx), ffprobe, ffmpeg)
        comparison = compare_reports(mere, ltx)

        local_reference = inspect_local_reference(repo_root)
        upstream_reference = inspect_ltx_repo(Path(args.ltx_repo)) if args.ltx_repo else None
        model_reference = inspect_model_root(Path(args.model_root)) if args.model_root else None

        warnings = list(comparison["warnings"])
        warnings.extend(reference_warnings(local_reference, upstream_reference, model_reference))

        report = {
            "mere": mere,
            "ltx": ltx,
            "comparison": comparison,
            "references": {
                "local": local_reference,
                "ltx_repo": upstream_reference,
                "model_root": model_reference,
            },
            "warnings": warnings,
        }

        if args.json_out:
            output_path = Path(args.json_out)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")

        if not args.quiet:
            print_human_report(report)

        if warnings and args.fail_on_warning:
            return 2
        return 0
    except DiagnosticError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compare a mere.run unified-av MP4 against an upstream LTX-2 MP4 "
            "using ffprobe metadata, decoded PCM stats, and source-reference checks."
        )
    )
    parser.add_argument("--mere", required=True, help="MP4 generated by mere.run --variant unified-av.")
    parser.add_argument("--ltx", required=True, help="MP4 generated by the upstream LTX-2 pipeline.")
    parser.add_argument(
        "--ltx-repo",
        help="Optional path to a local Lightricks/LTX-2 checkout for source-default inspection.",
    )
    parser.add_argument(
        "--model-root",
        help="Optional local video-ltx-av model root to scan for audio/vocoder config hints.",
    )
    parser.add_argument("--json-out", help="Optional path for a full JSON report.")
    parser.add_argument("--fail-on-warning", action="store_true", help="Exit 2 when drift warnings are detected.")
    parser.add_argument("--quiet", action="store_true", help="Only write --json-out; do not print the text report.")
    return parser.parse_args()


class DiagnosticError(RuntimeError):
    pass


def resolve_tool(env_name: str, default_name: str) -> str:
    override = os.environ.get(env_name)
    if override:
        if Path(override).is_file() and os.access(override, os.X_OK):
            return override
        raise DiagnosticError(f"{env_name} points to a non-executable file: {override}")

    resolved = shutil.which(default_name)
    if resolved:
        return resolved
    raise DiagnosticError(f"{default_name} was not found on PATH; install ffmpeg or set {env_name}.")


def run_command(command: list[str], *, text: bool = True) -> subprocess.CompletedProcess[str] | subprocess.CompletedProcess[bytes]:
    try:
        return subprocess.run(command, check=False, capture_output=True, text=text)
    except OSError as error:
        raise DiagnosticError(f"failed to run {command[0]}: {error}") from error


def analyze_media(path: Path, ffprobe: str, ffmpeg: str) -> dict[str, Any]:
    if not path.is_file():
        raise DiagnosticError(f"media file does not exist: {path}")

    probe = ffprobe_json(path, ffprobe)
    audio = first_stream(probe, "audio")
    video = first_stream(probe, "video")
    if audio is None:
        raise DiagnosticError(f"{path} has no audio stream")

    sample_rate = int_or_none(audio.get("sample_rate"))
    highpass_cutoff = highpass_cutoff_for(sample_rate)
    pcm = pcm_stats(path, ffmpeg)
    high = pcm_stats(path, ffmpeg, audio_filter=f"highpass=f={highpass_cutoff}")
    loudness = ebur128_stats(path, ffmpeg)

    highpass_ratio_db = None
    if pcm["rms_linear"] and high["rms_linear"]:
        highpass_ratio_db = db(high["rms_linear"] / pcm["rms_linear"])

    return {
        "path": str(path),
        "format": summarize_format(probe.get("format", {})),
        "audio_stream": summarize_audio_stream(audio),
        "video_stream": summarize_video_stream(video) if video else None,
        "decoded_audio": {
            **pcm,
            "highpass_cutoff_hz": highpass_cutoff,
            "highpass_rms_dbfs": high["rms_dbfs"],
            "highpass_to_full_rms_db": highpass_ratio_db,
        },
        "loudness": loudness,
    }


def ffprobe_json(path: Path, ffprobe: str) -> dict[str, Any]:
    result = run_command(
        [
            ffprobe,
            "-v",
            "error",
            "-show_format",
            "-show_streams",
            "-of",
            "json",
            str(path),
        ]
    )
    if result.returncode != 0:
        raise DiagnosticError(f"ffprobe failed for {path}: {result.stderr.strip()}")
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise DiagnosticError(f"ffprobe returned invalid JSON for {path}: {error}") from error


def first_stream(probe: dict[str, Any], kind: str) -> dict[str, Any] | None:
    for stream in probe.get("streams", []):
        if stream.get("codec_type") == kind:
            return stream
    return None


