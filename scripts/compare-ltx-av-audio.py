def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def read_first_text(root: Path, relative_paths: list[str]) -> tuple[Path | None, str]:
    for relative_path in relative_paths:
        path = root / relative_path
        text = read_text(path)
        if text:
            return path, text
    return None, ""


def extract_swift_func(text: str, signature: str) -> str:
    start = text.find(signature)
    if start < 0:
        return ""
    brace = text.find("{", start)
    if brace < 0:
        return ""
    depth = 0
    for index in range(brace, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]
    return text[start:]


def git_commit(repo: Path) -> str | None:
    result = run_command(["git", "-C", str(repo), "rev-parse", "HEAD"])
    if result.returncode == 0:
        return result.stdout.strip()
    return None


def regex_group(pattern: str, text: str) -> str | None:
    match = re.search(pattern, text)
    return match.group(1) if match else None


def maybe_append_int(values: list[int], value: Any) -> None:
    parsed = int_or_none(value)
    if parsed is not None:
        values.append(parsed)


def int_or_none(value: Any) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def float_or_none(value: Any) -> float | None:
    if value is None:
        return None
    try:
        parsed = float(value)
    except (TypeError, ValueError):
        return None
    if math.isfinite(parsed):
        return parsed
    return None


def fraction_to_float(value: Any) -> float | None:
    if not isinstance(value, str) or "/" not in value:
        return float_or_none(value)
    numerator, denominator = value.split("/", 1)
    num = float_or_none(numerator)
    den = float_or_none(denominator)
    if num is None or den in (None, 0):
        return None
    return num / den


def last_float_match(pattern: str, text: str) -> float | None:
    matches = re.findall(pattern, text)
    if not matches:
        return None
    return float_or_none(matches[-1])


def delta(left: Any, right: Any) -> float | None:
    left_float = float_or_none(left)
    right_float = float_or_none(right)
    if left_float is None or right_float is None:
        return None
    return left_float - right_float


def db(value: float) -> float:
    if value <= 0 or not math.isfinite(value):
        return float("-inf")
    return 20.0 * math.log10(value)


def none_if_inf(value: float) -> float | None:
    return value if math.isfinite(value) else None


def highpass_cutoff_for(sample_rate: int | None) -> int:
    if not sample_rate:
        return 8000
    nyquist = sample_rate / 2
    return int(max(2000, min(8000, nyquist * 0.70)))


def format_value(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def format_bitrate(value: Any) -> str:
    parsed = int_or_none(value)
    if parsed is None:
        return "n/a"
    return f"{parsed / 1000:.1f} kbps"


def format_db(value: Any, suffix: str) -> str:
    parsed = float_or_none(value)
    if parsed is None:
        return "n/a"
    return f"{parsed:.2f} {suffix}"


def format_percent(value: Any) -> str:
    parsed = float_or_none(value)
    if parsed is None:
        return "n/a"
    return f"{parsed * 100:.4f}%"


