import Foundation
import MLX
import MLXNN

public struct IdolCamera: Codable, Equatable, Sendable {
    public let yaw: Float
    public let pitch: Float
    public let radius: Float
    public let fov: Float

    public static func decode(_ values: [Float]) throws -> Self {
        guard values.count == 5, values.allSatisfy(\.isFinite) else {
            throw IdolError.invalidInput("Camera latent must contain five finite values.")
        }
        let length = sqrt(values[0] * values[0] + values[1] * values[1] + values[2] * values[2])
        let direction: [Float] = length > 1e-6 ? values.prefix(3).map { $0 / length } : [0, 0, 1]
        let radius: Float = values[3] < 1e-3 ? 1000 : 1 / values[3]
        return Self(yaw: atan2(direction[0], direction[1]), pitch: asin(min(max(direction[2], -1), 1)),
                    radius: radius, fov: 2 * atan(values[4] / radius) * 180 / .pi)
    }
}

/// Activated, z-up splats. PLY export rotates positions and Hamilton quaternions to y-up.
public struct IdolGaussians {
    public let positions: MLXArray
    public let featuresDC: MLXArray
    public let scaling: MLXArray
    public let rotation: MLXArray
    public let opacity: MLXArray

    init(rawPositions: MLXArray, featuresDC: MLXArray, rawScaling: MLXArray, rawRotation: MLXArray,
         rawOpacity: MLXArray, configuration: IdolConfiguration.Representation) {
        positions = rawPositions - 0.5
        self.featuresDC = featuresDC
        let scalingOffset = configuration.scaling_bias + log(-expm1(-configuration.scaling_bias))
        let scales = softplus(rawScaling + scalingOffset)
        scaling = sqrt(scales * scales + configuration.filterKernelSize * configuration.filterKernelSize)
        let quaternions = rawRotation + MLXArray([Float(1), 0, 0, 0])
        rotation = quaternions / maximum(sqrt(sum(quaternions * quaternions, axis: -1, keepDims: true)), MLXArray(Float(1e-12)))
        opacity = sigmoid(rawOpacity + log(configuration.opacity_bias / (1 - configuration.opacity_bias)))
    }

    public var count: Int { positions.dim(0) }

    /// Binary little-endian standard 3DGS PLY, with log scales and opacity logits.
    public func plyData() throws -> Data {
        let xyz = positions.asArray(Float.self), dc = featuresDC.asArray(Float.self)
        let scales = log(maximum(scaling, MLXArray(Float(1e-6)))).asArray(Float.self)
        let alpha = clip(opacity, min: Float(1e-6), max: 1 - Float(1e-6))
        let logits = log(alpha / (1 - alpha)).asArray(Float.self), quaternions = rotation.asArray(Float.self)
        guard [xyz, dc, scales, logits, quaternions].allSatisfy({ $0.allSatisfy(\.isFinite) }) else {
            throw IdolError.invalidInput("Generated splats contain nonfinite values.")
        }
        let names = ["x", "y", "z", "nx", "ny", "nz", "f_dc_0", "f_dc_1", "f_dc_2", "opacity",
                     "scale_0", "scale_1", "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"]
        let header = "ply\nformat binary_little_endian 1.0\ncomment Generated by mere.run native IDOL\nelement vertex \(count)\n"
            + names.map { "property float \($0)\n" }.joined() + "end_header\n"
        var result = Data(header.utf8)
        result.reserveCapacity(result.count + count * 17 * 4)
        let root = sqrt(Float(0.5))
        for index in 0..<count {
            let p = index * 3, r = index * 4
            let w = quaternions[r], x = quaternions[r + 1], y = quaternions[r + 2], z = quaternions[r + 3]
            let row: [Float] = [xyz[p], -xyz[p + 2], xyz[p + 1], 0, 0, 0, dc[p], dc[p + 1], dc[p + 2], logits[index],
                scales[p], scales[p + 1], scales[p + 2], root * (w - x), root * (x + w), root * (y - z), root * (z + y)]
            for value in row {
                var bits = value.bitPattern.littleEndian
                withUnsafeBytes(of: &bits) { result.append(contentsOf: $0) }
            }
        }
        return result
    }
}
