import AudioDrama3Model
import Foundation
import MLX
import MereRunExecution
import MereRunTensor

public enum Drama3Resources {
    public static let modelID = "speech-tts-drama-3"
    public static let repository = "fishaudio/drama-3"
    public static let revision = "dd64a85cd82e9521f7202610ede97b367fc83946"
    public static let codecSHA256 = "74fc41c5a7151c6f350af8bd7e5d6e3accfcc7f3dfbfac23afd35af07052bb2f"

    public static func configuration(root: URL) throws -> Drama3Config {
        try JSONDecoder().decode(Drama3Config.self, from: Data(contentsOf: root.appendingPathComponent("config.json")))
    }

    public static func isDrama3(root: URL) -> Bool { (try? configuration(root: root)) != nil }

    public static func missingFiles(root: URL, fileManager: FileManager) -> [URL] {
        let files = ["config.json", "tokenizer.json", "tokenizer_config.json", "codec.pth", "LICENSE", "model.safetensors.index.json"]
        var missing = files.map { root.appendingPathComponent($0) }.filter { !fileManager.fileExists(atPath: $0.path) }
        if let data = try? Data(contentsOf: root.appendingPathComponent("model.safetensors.index.json")),
           let index = try? JSONDecoder().decode(HFSafetensorsIndex.self, from: data) {
            missing += index.shardFilenames.map { root.appendingPathComponent($0) }.filter { !fileManager.fileExists(atPath: $0.path) }
        }
        return missing
    }

    #if !os(iOS)
    public static func loadCodec(root: URL) throws -> Drama3Codec {
        #if canImport(ObjectiveC)
        return try autoreleasepool { try loadVerifiedCodec(root: root) }
        #else
        return try loadVerifiedCodec(root: root)
        #endif
    }

    private static func loadVerifiedCodec(root: URL) throws -> Drama3Codec {
        let url = root.appendingPathComponent("codec.pth")
        guard try RunArtifact.read(url).sha256 == codecSHA256 else {
            throw Drama3Error.invalid("codec.pth does not match the pinned DRAMA-3 codec SHA-256")
        }
        // The trusted whole-file digest supersedes the slow per-entry CRC pass;
        // all restricted ZIP/pickle structure and tensor checks remain enabled.
        let archive = try PyTorchStateDictArchive(url: url, verifyEntryChecksums: false)
        var weights: [String: MLXArray] = [:]
        for tensor in archive.tensors {
            // Rotary/mask buffers are deterministic, generated by the native graph.
            if tensor.name.hasSuffix(".freqs_cis") || tensor.name.hasSuffix(".causal_mask") { continue }
            let value = try archive.loadArray(for: tensor, dtype: .float32)
            MLX.eval(value)
            weights[tensor.name] = value
        }
        return try Drama3Codec(weights: weights)
    }
    #endif
}
